def get_course_system():
    return COURSE_SYSTEM


def get_knowledge_needs():
    """从课程体系倒推所有知识需求(去重)。CEO据此构建自动化管道。"""
    needs = {}
    for module in COURSE_SYSTEM["modules"]:
        for lesson in module["lessons"]:
            for need in lesson.get("knowledge_needs", []):
                needs[need] = needs.get(need, 0) + 1

    # 按引用频率排序(被越多课引用=越重要)
    sorted_needs = sorted(needs.items(), key=lambda x: x[1], reverse=True)

    return {
        "total_unique_needs": len(sorted_needs),
        "by_priority": {
            "P0_核心": [n for n, c in sorted_needs if c >= 3],
            "P1_重要": [n for n, c in sorted_needs if c == 2],
            "P2_支撑": [n for n, c in sorted_needs if c == 1],
        },
        "all_needs": [{"knowledge": n, "lesson_count": c} for n, c in sorted_needs],
    }
